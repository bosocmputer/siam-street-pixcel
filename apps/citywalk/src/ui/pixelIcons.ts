export type IconName = keyof typeof ICONS;

/** One <path> per colour: a run of pixels in a row is one rectangle. */
export function gridPaths(rows: readonly string[]): Map<string, string> {
  const paths = new Map<string, string>();
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x]!;
      let n = 1;
      while (row[x + n] === ch) n++;
      if (ch !== '.') paths.set(ch, (paths.get(ch) ?? '') + `M${x} ${y}h${n}v1h${-n}z`);
      x += n;
    }
  });
  return paths;
}

/** An SVG of a pixel picture, `cls` on the <svg>. */
export function pxSvg(rows: readonly string[], cls = 'px-ico'): string {
  const w = rows[0]?.length ?? 0;
  let body = '';
  for (const [ch, d] of gridPaths(rows))
    body += `<path d="${d}" fill="${ch === '#' ? 'currentColor' : (PALETTE[ch] ?? 'currentColor')}"/>`;
  return `<svg class="${cls}" viewBox="0 0 ${w} ${rows.length}" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}

export const pxIcon = (name: IconName, cls?: string): string => pxSvg(ICONS[name], cls);

/** A ring of pixels `n` across, `t` thick (a stepped circle, like one drawn by hand). */
export function pxRing(n: number, t: number): string[] {
  const c = (n - 1) / 2;
  const r = n / 2;
  return Array.from({ length: n }, (_, y) =>
    Array.from({ length: n }, (_, x) => {
      const d = Math.hypot(x - c, y - c);
      return d < r - 0.1 && d >= r - t - 0.1 ? '#' : '.';
    }).join(''),
  );
}
